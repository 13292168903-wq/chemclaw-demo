// ===== 结构几何：单一实现 =====
//
// 这个文件同时被浏览器（/shared/structure.js）和 Node 服务端
// （src/orchestrator.js 通过相对路径 import）使用，因此必须保持
// 纯函数、无 DOM、无 Node API。
//
// 之前前后端各有一份 parseXYZAtoms / computeBonds，共价半径和容差
// 常量也各写一遍 —— 两份实现迟早会漂移，而它们是"键"这个化学事实的
// 唯一来源，漂移意味着同一份数据在 3D 卡片和 2D 兜底里画出不同的键。

/** 共价半径（Å），Cordero et al. 2008，取舍到两位小数。 */
export const COVALENT_RADII = {
  H: 0.31, He: 0.28, Li: 1.28, Be: 0.96, B: 0.84, C: 0.76, N: 0.71, O: 0.66,
  F: 0.57, Ne: 0.58, Na: 1.66, Mg: 1.41, Al: 1.21, Si: 1.11, P: 1.07, S: 1.05,
  Cl: 1.02, Ar: 1.06, K: 2.03, Ca: 1.76, Ti: 1.60, V: 1.53, Cr: 1.39, Mn: 1.39,
  Fe: 1.32, Co: 1.26, Ni: 1.24, Cu: 1.32, Zn: 1.22, Ga: 1.22, Ge: 1.20, As: 1.19,
  Se: 1.20, Br: 1.20, Kr: 1.16, Ru: 1.46, Rh: 1.42, Pd: 1.39, Ag: 1.45, Cd: 1.44,
  In: 1.42, Sn: 1.39, Sb: 1.39, Te: 1.38, I: 1.39, Xe: 1.40, W: 1.62, Re: 1.51,
  Os: 1.44, Ir: 1.41, Pt: 1.36, Au: 1.36, Hg: 1.32, Pb: 1.46, Bi: 1.48,
};

/** 成键判据的松弛系数：d < (r1 + r2) * BOND_TOLERANCE。 */
export const BOND_TOLERANCE = 1.28;

/** 元素在 2D 投影里的配色。 */
export const ELEMENT_COLORS = {
  H: "#f1f5f9", C: "#334155", N: "#2563eb", O: "#dc2626",
  F: "#16a34a", P: "#d97706", S: "#eab308", Cl: "#15803d",
  Br: "#92400e", I: "#7c3aed", Si: "#64748b", B: "#f59e0b",
};

/** 2D 投影里的原子半径（像素）。 */
export const ELEMENT_RADII_2D = { H: 9, C: 15, N: 14, O: 14, F: 13, S: 16, P: 16, Cl: 16 };

const ELEMENT_RE = /^[A-Z][a-z]?$/;

/**
 * 解析 XYZ / 只含坐标行的文本。
 * 首行若是纯数字（标准 XYZ 的原子数）则跳过前两行。
 * @returns {Array<{element: string, x: number, y: number, z: number}>}
 */
export function parseXYZAtoms(text = "") {
  const lines = String(text).trim().split(/\r?\n/);
  const start = /^\d+$/.test(lines[0]?.trim() || "") ? 2 : 0;
  const atoms = [];
  for (const line of lines.slice(start)) {
    const parts = line.trim().split(/\s+/);
    if (parts.length < 4 || !ELEMENT_RE.test(parts[0])) continue;
    const [element, x, y, z] = [parts[0], Number(parts[1]), Number(parts[2]), Number(parts[3])];
    if (Number.isFinite(x) && Number.isFinite(y) && Number.isFinite(z)) atoms.push({ element, x, y, z });
  }
  return atoms;
}

/** 从 PDB 文本里取原子坐标（cols 31-54 为 x/y/z，元素列 77-78）。 */
export function parsePdbAtoms(pdbText = "") {
  return String(pdbText).split(/\r?\n/)
    .filter((line) => /^(ATOM|HETATM)/.test(line))
    .map((line) => {
      const x = Number(line.slice(30, 38));
      const y = Number(line.slice(38, 46));
      const z = Number(line.slice(46, 54));
      let element = line.slice(76, 78).trim();
      if (!element) {
        const name = line.slice(12, 16).trim();
        element = (name.match(/^[A-Za-z]/)?.[0] || "C").toUpperCase();
      }
      return Number.isFinite(x) && Number.isFinite(y) && Number.isFinite(z) ? { element, x, y, z } : null;
    })
    .filter(Boolean);
}

/**
 * 距离判据成键（不区分键级）。
 * @returns {Array<[number, number]>} 原子下标对，i < j
 */
export function computeBonds(atoms = [], { tolerance = BOND_TOLERANCE } = {}) {
  const bonds = [];
  for (let i = 0; i < atoms.length; i++) {
    for (let j = i + 1; j < atoms.length; j++) {
      const a = atoms[i];
      const b = atoms[j];
      const dist = Math.hypot(a.x - b.x, a.y - b.y, a.z - b.z);
      const r1 = COVALENT_RADII[a.element] || 0.76;
      const r2 = COVALENT_RADII[b.element] || 0.76;
      if (dist > 0.25 && dist < (r1 + r2) * tolerance) bonds.push([i, j]);
    }
  }
  return bonds;
}

/**
 * XYZ → PDB（带 CONECT），供 Mol* 直接加载。
 * 也接受只含坐标行的文本。
 */
export function toPDB(xyzText, title = "ChemClaw") {
  const atoms = parseXYZAtoms(xyzText);
  if (!atoms.length) return "";

  const bonds = computeBonds(atoms);
  const lines = [
    `HEADER    ${title}`,
    `TITLE     ${title}`,
    `REMARK   Generated by ChemClaw - ${atoms.length} atoms, ${bonds.length} bonds`,
  ];

  atoms.forEach((atom, i) => {
    const serial = String(i + 1).padStart(5);
    const name = atom.element.padEnd(4);
    const x = atom.x.toFixed(3).padStart(8);
    const y = atom.y.toFixed(3).padStart(8);
    const z = atom.z.toFixed(3).padStart(8);
    lines.push(`ATOM  ${serial} ${name} MOL A   1    ${x}${y}${z}  1.00  0.00          ${atom.element.padStart(2)}`);
  });

  // CONECT 每行最多 4 个伙伴原子（PDB 规范）
  const conectMap = new Map();
  for (const [i, j] of bonds) {
    if (!conectMap.has(i)) conectMap.set(i, []);
    if (!conectMap.has(j)) conectMap.set(j, []);
    conectMap.get(i).push(j + 1);
    conectMap.get(j).push(i + 1);
  }
  for (const [index, partners] of [...conectMap.entries()].sort((a, b) => a[0] - b[0])) {
    const sorted = [...new Set(partners)].sort((a, b) => a - b);
    for (let k = 0; k < sorted.length; k += 4) {
      lines.push(`CONECT${String(index + 1).padStart(5)}${sorted.slice(k, k + 4).map((c) => String(c).padStart(5)).join("")}`);
    }
  }

  lines.push("END");
  return lines.join("\n");
}

/**
 * 固定视角的 2D 投影（无 WebGL 时的兜底渲染）。
 * 返回屏幕坐标与配色，不依赖 DOM，便于测试。
 */
export function projectAtoms2D(atoms, { width = 520, height = 360 } = {}) {
  if (!atoms.length) return { width, height, projected: [] };

  const cx = atoms.reduce((s, a) => s + a.x, 0) / atoms.length;
  const cy = atoms.reduce((s, a) => s + a.y, 0) / atoms.length;
  const cz = atoms.reduce((s, a) => s + a.z, 0) / atoms.length;
  const cosY = Math.cos(0.75), sinY = Math.sin(0.75);
  const cosX = Math.cos(-0.55), sinX = Math.sin(-0.55);

  const raw = atoms.map((atom) => {
    const x0 = atom.x - cx, y0 = atom.y - cy, z0 = atom.z - cz;
    const x1 = x0 * cosY + z0 * sinY;
    const z1 = -x0 * sinY + z0 * cosY;
    const y1 = y0 * cosX - z1 * sinX;
    return { ...atom, px: x1, py: y1 };
  });

  const span = Math.max(
    Math.max(...raw.map((a) => a.px)) - Math.min(...raw.map((a) => a.px)),
    Math.max(...raw.map((a) => a.py)) - Math.min(...raw.map((a) => a.py)),
    1,
  );
  const scale = (Math.min(width, height) * 0.62) / span;

  return {
    width,
    height,
    projected: raw.map((atom) => ({
      ...atom,
      x: Number((width / 2 + atom.px * scale).toFixed(1)),
      y: Number((height / 2 - atom.py * scale).toFixed(1)),
      color: ELEMENT_COLORS[atom.element] || "#7c8794",
      r: ELEMENT_RADII_2D[atom.element] || 12,
    })),
  };
}

/** 结构摘要，用于测试与日志。 */
export function summarizeStructure(atoms) {
  const composition = {};
  for (const atom of atoms) composition[atom.element] = (composition[atom.element] || 0) + 1;
  return { atomCount: atoms.length, bondCount: computeBonds(atoms).length, composition };
}
